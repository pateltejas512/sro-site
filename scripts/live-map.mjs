/* ---------------- exams & papers ---------------- */
export function examPaper(r) {
  const e = r.exam?.slug ?? '';
  const p = r.paper?.slug ?? '';
  if (e.startsWith('deputy-executive-engineer-electrical-class-2')) return ['gpsc-dee-electrical', '2026-dee-master-paper'];
  if (e.startsWith('assistant-engineer-electrical-class-2-road-and-building')) return ['gpsc-ae-electrical-class-2', '2025-ae-rnb-series-m'];
  if (e === 'supervisor-instructor-electrical-group') return ['gssb-supervisor-instructor-electrical', '2026-part-b-technical'];
  if (e === 'additional-assistant-engineer-electrical') return ['gpssb-aae-electrical', p === 'non-technical' ? '2026-cbrt-non-technical' : '2026-cbrt-technical'];
  if (e === 'bms') return ['gpsc-dee-electrical', '2024-dee-electrical']; // labelled "BMS" on WP; confirmed by SRO: GPSC DEE (Electrical) 2024
  if (e === 'vidyut-sahayak-junior-engineer-electrical') return ['guvnl-vidyut-sahayak-je', '2024-second-tier-electrical'];
  if (e.startsWith('railway-recruitment-boards')) return null; // already in data/rrb-je-2026-cbt2.ts
  throw new Error('Unmapped exam ' + e);
}

